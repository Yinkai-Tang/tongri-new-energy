export interface Business {
  /** URL 路径标识 */
  slug: string
  /** 中文标题 */
  name: string
  /** 英文标题 */
  nameEn: string
  /** 一句话定位 */
  tagline: string
  /** 首页/总览卡片摘要 */
  summary: string
  /** 序号（01/02/03） */
  index: string
  /** 卡片与页头配图（public/images 下） */
  image: string
  imageAlt: string
  /** 详情页主题色：accent = 电光蓝，energy = 绿色 */
  theme: 'accent' | 'energy'
  /** 板块定位说明（详情页首段） */
  positioning: string[]
  /** 服务/能力范围 */
  capabilities: Capability[]
  /** 应用场景 */
  scenarios: { title: string; desc: string }[]
  /** 业务/协同流程 */
  processTitle: string
  process: ProcessStep[]
  /** 合作咨询引导语 */
  ctaText: string
}

